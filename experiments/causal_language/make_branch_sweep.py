"""Write a causal branch sweep (3 arms) from a seed run.

Removal (a seed that hacked after saying X in the reasoning of request k):
  keep     prefix_through X            -- X stays, the model continues right after it
  cut      prefix_until X              -- rewind to just before X; the model may say X again
  replace  prefix_until X + neutral N  -- X swapped for a neutral sentence of similar length
Injection (a clean seed; insert X after anchor sentence A in the reasoning of request k):
  inject   prefix_through A + " X"
  none     prefix_through A            -- same cut point, nothing added
  neutral  prefix_through A + " N"

Usage (repo root):
  python experiments/causal_language/make_branch_sweep.py removal  <seed_sweep.yaml> <seed_run_dir> <k> \\
      --x "<sentence>" --neutral "<sentence>" [--reps 20] [--workers 10] --name <short_name>
  python experiments/causal_language/make_branch_sweep.py injection <seed_sweep.yaml> <seed_run_dir> <k> \\
      --anchor "<sentence>" --x "<sentence>" --neutral "<sentence>" [--reps 20] --name <short_name>
Everything but pressure/branch/n_reps/output comes from the seed sweep (task, behaviors,
final score, judge), so branches are scored and judged exactly like their seeds.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("direction", choices=["removal", "injection"])
    ap.add_argument("seed_sweep")
    ap.add_argument("seed_run")
    ap.add_argument("request", type=int)
    ap.add_argument("--x", required=True)
    ap.add_argument("--neutral", required=True)
    ap.add_argument("--anchor")
    ap.add_argument("--reps", type=int, default=20)
    ap.add_argument("--workers", type=int, default=10)
    ap.add_argument("--name", required=True)
    a = ap.parse_args()

    cfg = yaml.safe_load(Path(a.seed_sweep).read_text())
    x, n = a.x.strip(), a.neutral.strip()
    if a.direction == "removal":
        arms = {"keep": {"prefix_through": x},
                "cut": {"prefix_until": x},
                "replace": {"prefix_until": x, "append": n}}
    else:
        if not a.anchor:
            raise SystemExit("injection needs --anchor (the sentence after which X is inserted)")
        anchor = a.anchor.strip()
        arms = {"inject": {"prefix_through": anchor, "append": " " + x},
                "none": {"prefix_through": anchor},
                "neutral": {"prefix_through": anchor, "append": " " + n}}
    name = f"causal_branch_{a.name}"
    for k in ("prompt_variants", "experiment_name", "output_dir", "pressure", "n_reps",
              "n_trajectory_workers", "branch"):
        cfg.pop(k, None)
    out = {
        "experiment_name": name,
        "output_dir": f"pipeline_runs/{name}",
        "pressure": {"variable": "branch_arm", "values": list(arms)},
        "n_reps": a.reps,
        "n_trajectory_workers": a.workers,
        "branch": {"seed_run": a.seed_run, "request": a.request, "arms": arms},
        **cfg,
    }
    path = Path("experiments/causal_language") / f"branch_{a.name}.yaml"
    head = (f"# Causal-language experiment: {a.direction} branch sweep from {a.seed_run} (request {a.request}).\n"
            f"# Generated by experiments/causal_language/make_branch_sweep.py; X = {x!r}\n")
    path.write_text(head + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=100))
    print(path)


if __name__ == "__main__":
    main()
